private fun finishPush(seconds: Int) =
    s("Добивай!", seconds, BURST, "Конец раунда — выложи всё, что осталось")

private fun sparringRound(title: String, gap: IntRange, bursts: List<Burst> = ALL_BURSTS, finish: Int = 10) = Block(
    title = title,
    type = BlockType.ROUND,
    parts = listOf(Part.Sparring(180, bursts, gap, finish = finishPush(finish))),
    intro = "$title. Жди взрывов",
)

/** 20 s on / 10 s off × 8, alternating two exercises; ends on work so the bell closes the round. */
private fun tabataRound(title: String, a: Step, b: Step): Block {
    val breath = s("Вдох", 10, REST, "Встряхни руки, выдохни", say = "")
    val steps = (0 until 8).flatMap { i ->
        val work = if (i % 2 == 0) a else b
        if (i < 7) listOf(work, breath) else listOf(work)
    }
    return Block(title, BlockType.ROUND, steps.map { Part.Fixed(it) })
}

/** One minute per rung: a burst at the top of the minute, the rest of it to recover on the move. */
private fun ladderRound(title: String, bursts: List<Pair<String, String>>): Block {
    val steps = listOf(10, 20, 30, 40, 50, 40, 30, 20, 10).flatMapIndexed { i, seconds ->
        val (name, hint) = bursts[i % bursts.size]
        listOf(
            s(name, seconds, BURST, hint, say = "$seconds секунд! $name!"),
            s("Восстановление в движении", 60 - seconds, PRESSURE, "Джеб, работа ног, дыхание. Не стой на месте", say = "Восстановление"),
        )
    }
    return Block(title, BlockType.ROUND, steps.map { Part.Fixed(it) })
}

